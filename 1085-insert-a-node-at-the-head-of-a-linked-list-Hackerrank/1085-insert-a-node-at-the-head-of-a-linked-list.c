/*
 * For your reference:
 *
 * SinglyLinkedListNode {
 *     int data;
 *     SinglyLinkedListNode* next;
 * };
 *
 */
SinglyLinkedListNode* insertNodeAtHead(SinglyLinkedListNode* llist, int data) {
    struct SinglyLinkedListNode *newnode=malloc(sizeof(int));
    newnode->data=data;
    newnode->next=llist;
    
    if(llist==NULL){
        return newnode;
    }
    return newnode;
    
}



